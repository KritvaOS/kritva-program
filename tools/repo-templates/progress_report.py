"""Render or check status/STATUS.md from status/program_snapshot.json.

  progress_report.py --write    regenerate status/STATUS.md
  progress_report.py --check    exit 1 if status/STATUS.md differs from what the snapshot renders

The snapshot is this repository's slice of the kritva-program consolidated status, copied in by
kritva-program (tools/publish_repo_progress.py). This script does not read the program repository and
makes no network call, so a change of program data never turns this check red by itself. A refresh is
a deliberate pull request.

The bar shows ACCEPTED weight only, as decided by kritva-program. Execution, evidence, acceptance and
release readiness stay separate rows and are never merged into one figure (README standard section 7).
This repository sends facts only and earns no credit by itself; this file is a derived snapshot that can
lag the program. Standard library only.
"""
import argparse
import datetime as dt
import json
import sys
from pathlib import Path

SNAPSHOT = Path("status/program_snapshot.json")
REPORT = Path("status/STATUS.md")
STATUS_JSON = Path("status/status.json")
WIDTH = 20
STALE_DAYS = 14
SCHEMA_VERSION = 1
MILESTONES = ["M0", "M1", "M2", "M3", "M4", "M5", "M7", "M8"]  # M6 (physical validation) is on HOLD
REQUIRED = ["schema_version", "repo", "repository", "program", "foundation", "milestones", "baseline_tasks",
            "execution", "evidence_notes", "titles"]


def bar(done, total, width=WIDTH):
    n = 0 if not total else round(width * done / total)
    return "█" * n + "░" * (width - n)


def fmt(x):
    return f"{x:g}"


def share(done, total):
    return f"{100 * done / total:.1f}%" if total else "n/a"


def rows(snap):
    """Progress rows: (label, accepted weight, total weight). Foundation first, then the V2 milestones."""
    out = []
    f = snap["foundation"]
    if f["weight"]:
        out.append(("Foundation (PRE_V2)", f["accepted_weight"], f["weight"]))
    for m in MILESTONES:
        v = snap["milestones"].get(m)
        if not v or not (v["baseline"] + v["point"]):
            continue
        title = snap["titles"].get(m, "")
        out.append((f"{m} {title}".strip(), v["accepted"], v["baseline"] + v["point"]))
    return out


def totals(snap):
    r = rows(snap)
    b = snap["baseline_tasks"]
    f = snap["foundation"]
    return {"accepted": sum(x[1] for x in r), "total": sum(x[2] for x in r),
            "accepted_tasks": f["accepted_tasks"] + b["accepted_tasks"],
            "tasks": f["tasks"] + b["baseline_tasks"] + b["rows"]}


def validate(snap):
    problems = [f"snapshot field missing: {k}" for k in REQUIRED if k not in snap]
    if problems:
        return problems
    if snap["schema_version"] != SCHEMA_VERSION:
        problems.append(f"snapshot schema_version {snap['schema_version']} is not {SCHEMA_VERSION}")
    t = totals(snap)
    if t["accepted"] > t["total"]:
        problems.append("accepted weight is larger than total weight")
    for label, a, n in rows(snap):
        if a > n:
            problems.append(f"{label}: accepted weight {fmt(a)} is larger than total {fmt(n)}")
    return problems


def render(snap):
    t = totals(snap)
    p = snap["program"]
    ex = snap["execution"]
    L = ["<!-- GENERATED by scripts/progress_report.py from status/program_snapshot.json. Do not edit by hand. -->", "",
         f"# Progress: {snap['repository']}", "",
         f"Derived snapshot of the kritva-program status view, taken {p['generated_at']} at baseline v{p['baseline_version']}"
         f"{' (APPROVED)' if p.get('baseline_approved') else ' (NOT APPROVED)'}. It can lag the program. "
         f"The program view is the record: [{p['view']}]({p['view']}).", "",
         "This repository sends facts only and earns no program credit by itself. Acceptance is decided by kritva-program, "
         "and this file never approves anything.", "",
         "## Accepted progress", "",
         "```text",
         f"Accepted weight: {share(t['accepted'], t['total'])}  ({fmt(t['accepted'])} / {fmt(t['total'])} weight, "
         f"{t['accepted_tasks']} of {t['tasks']} tasks)",
         bar(t["accepted"], t["total"]), "```", "",
         "Accepted weight over total weight, where total covers completed Foundation work, baselined V2 tasks and "
         "owner-approved V2 planning tasks that are not baselined yet. Planning-only tasks are in the total and earn "
         "nothing until they are baselined and accepted. Weights are estimates.", "",
         "## Milestones", "",
         "| Milestone | Progress | Accepted / total weight | Share |", "|---|---|---|---|"]
    for label, a, n in rows(snap):
        L.append(f"| {label} | `{bar(a, n)}` | {fmt(a)} / {fmt(n)} | {share(a, n)} |")
    L.append(f"| **All** | `{bar(t['accepted'], t['total'])}` | **{fmt(t['accepted'])} / {fmt(t['total'])}** | **{share(t['accepted'], t['total'])}** |")
    L += ["", "Milestone dates are owner-approved planning dates in the program, not delivery commitments.", "",
          "## Four states, kept apart", "",
          "| State | This repository | Decided by |", "|---|---|---|",
          f"| Execution | {ex['complete']} of {ex['tasks']} baselined tasks reported COMPLETE by this repository | this repository's own report |",
          "| Evidence | " + ("; ".join(snap["evidence_notes"]) if snap["evidence_notes"] else "no evidence gap recorded for this repository in the program's evidence health")
          + " | the program's CI run verification |",
          f"| Acceptance | {fmt(t['accepted'])} / {fmt(t['total'])} weight (bar above) | kritva-program approvals |",
          f"| Release readiness | {p['release_state']} for the program; this progress figure is not readiness | program gates |", "",
          "Reported execution is not acceptance, and a bar is not release readiness. Refresh this file by running "
          "`tools/publish_repo_progress.py` in kritva-program and merging the resulting pull request here.", ""]
    return "\n".join(L)


def load(root):
    return json.loads((root / SNAPSHOT).read_text(encoding="utf-8"))


def identity_problem(root, snap):
    sj = root / STATUS_JSON
    if sj.is_file():
        repo = json.loads(sj.read_text(encoding="utf-8")).get("repo")
        if repo and repo != snap.get("repository"):
            return f"snapshot is for {snap.get('repository')} but {STATUS_JSON} reports {repo}"
    return None


def age_warning(snap, now=None):
    try:
        got = dt.datetime.strptime(snap["program"]["generated_at"], "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=dt.timezone.utc)
    except (KeyError, ValueError):
        return "snapshot generated_at is missing or not in YYYY-MM-DDTHH:MM:SSZ form"
    days = ((now or dt.datetime.now(dt.timezone.utc)) - got).days
    return f"snapshot is {days} days old (program reports older than {STALE_DAYS} days are treated as stale); refresh it" if days > STALE_DAYS else None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=".")
    a = ap.parse_args(argv)
    root = Path(a.root)
    if not (root / SNAPSHOT).is_file():
        print(f"progress_report: {SNAPSHOT} not found")
        return 1
    snap = load(root)
    problems = validate(snap)
    ident = None if problems else identity_problem(root, snap)
    if ident:
        problems.append(ident)
    if problems:
        for x in problems:
            print(f"FAIL {x}")
        return 1
    text = render(snap)
    warn = age_warning(snap)
    if warn:
        print(f"WARN {warn}")
    if a.write:
        (root / REPORT).write_text(text, encoding="utf-8")
        print(f"progress_report: wrote {REPORT}")
        return 0
    have = (root / REPORT).read_text(encoding="utf-8") if (root / REPORT).is_file() else None
    if have != text:
        print(f"FAIL {REPORT} does not match {SNAPSHOT}: run `python3 scripts/progress_report.py --write`")
        return 1
    print(f"progress_report: PASS ({REPORT} matches {SNAPSHOT})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
